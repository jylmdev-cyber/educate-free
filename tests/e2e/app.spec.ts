test('respaldo: exportación, importación revisable y rechazo de archivo ajeno', async ({ page }) => {
  await page.goto('./#/rutas')
  await page.getByRole('checkbox', { name: 'Completar Excel básico', exact: true }).check()
  const downloadWait = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar respaldo de progreso' }).click()
  const download = await downloadWait
  const file = await download.path()
  await page.getByRole('checkbox', { name: 'Completar Excel básico', exact: true }).uncheck()
  await page.locator('input[type=file]').setInputFiles(file!)
  await expect(page.getByRole('dialog')).toContainText('Importar tu progreso')
  await page.getByRole('button', { name: 'Reemplazar con este respaldo' }).click()
  await expect(page.getByRole('checkbox', { name: 'Completar Excel básico', exact: true })).toBeChecked()
  await page.locator('input[type=file]').setInputFiles({ name: 'ajeno.json', mimeType: 'application/json', buffer: Buffer.from('{}') })
  await expect(page.getByRole('status')).toContainText('Selecciona un respaldo')
  await expect(page.getByRole('checkbox', { name: 'Completar Excel básico', exact: true })).toBeChecked()
})
test('cinco vistas, gráficos, radar y navegación en subruta sin errores', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  for (const route of ['', '#/analisis', '#/recomendados', '#/rutas', '#/radar']) {
    await page.goto(`./${route}`)
    await expect(page.locator('h1')).toBeVisible()
    if (route.includes('analisis')) await expect(page.getByRole('heading', { name: '¿Qué puedes aprender?' })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)).toBe(false)
    const axe = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
    expect(axe.violations.map(v => ({ id: v.id, nodes: v.nodes.map(n => ({ target: n.target, issue: n.failureSummary })) }))).toEqual([])
    await page.screenshot({ path: `${evidenceDir}/screenshots/${testInfo.project.name}-${route.replace('#/', '') || 'catalogo'}.png`, fullPage: true })
  }
  await page.locator('.radar-card').first().getByRole('button', { name: 'Seguir', exact: true }).click()
  await page.getByLabel(/Solo las que sigo/).check()
  await expect(page.locator('.radar-card')).toHaveCount(1)
  await page.getByRole('button', { name: 'Marcar revisado' }).click()
  await expect(page.locator('.radar-card')).not.toContainText('Revisión personal: Pendiente')
  await page.reload()
  await page.getByLabel(/Solo las que sigo/).check()
  await expect(page.locator('.radar-card')).toHaveCount(1)
  expect(errors).toEqual([])
})
