test('popups: tamaños, opciones largas, borde de ventana y colores forzados', async ({ page }, testInfo) => {
  for (const width of [320, 393, 768, 1440]) {
    await page.setViewportSize({ width, height: 960 })
    await page.goto('./')
    for (const label of ['Ubicación', 'Área', 'Institución', 'Gratuidad', 'Inscripción', 'Duración', 'Ordenar oportunidades']) {
      const trigger = page.getByRole('combobox', { name: label, exact: true })
      expect((await trigger.boundingBox())!.height).toBeGreaterThanOrEqual(44)
      await trigger.click()
      const menu = page.getByRole('listbox')
      const box = (await menu.boundingBox())!
      expect(box.x).toBeGreaterThanOrEqual(0)
      expect(box.y).toBeGreaterThanOrEqual(0)
      expect(box.x + box.width).toBeLessThanOrEqual(width)
      expect(box.y + box.height).toBeLessThanOrEqual(960)
      await page.keyboard.press('Escape')
    }
    await choose(page, 'Institución', 'Ministerio de Trabajo y Promoción del Empleo / CAPACÍTA-T (MTPE)')
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
    await page.screenshot({ path: `${evidenceDir}/screenshots/${testInfo.project.name}-${width}-long-value.png` })
  }
  await page.emulateMedia({ forcedColors: 'active', reducedMotion: 'reduce' })
  await page.getByRole('combobox', { name: 'Institución', exact: true }).click()
  await expect(page.getByRole('option', { name: 'Todas las instituciones', exact: true })).toBeVisible()
  await page.screenshot({ path: `${evidenceDir}/screenshots/${testInfo.project.name}-forced-colors-menu.png` })
  await page.keyboard.press('Escape')
})


test('select de ficha: estado deshabilitado cuando no hay rutas', async ({ page }) => {
  await page.goto('./#/rutas')
  const downloadWait = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Exportar respaldo de progreso' }).click()
  const download = await downloadWait
  const backup = JSON.parse(await readFile((await download.path())!, 'utf8'))
  backup.data.routes = []
  await page.locator('input[type=file]').setInputFiles({ name: 'sin-rutas.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) })
  await page.getByRole('button', { name: 'Reemplazar con este respaldo' }).click()
  await page.goto('./')
  await page.getByRole('button', { name: 'Ver detalles' }).first().click()
  const route = page.getByRole('combobox', { name: 'Agregar a mi ruta', exact: true })
  await expect(route).toBeDisabled()
  await expect(route).toContainText('Crea una ruta primero')
  await expect(page.getByRole('dialog').getByRole('button', { name: 'Agregar', exact: true })).toBeDisabled()
  expect((await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([])
})
